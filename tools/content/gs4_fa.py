    order = [
        ("eevdf", "EEVDF (واجد شرایط + ددلاین مجازی)"),
        ("wfq_finish", "WFQ / PGPS (زمان پایان)"),
        ("gs_vtime:max_weight", "gs_vtime (تساوی بیشینه وزن)"),
        ("gs_vtime:index", "gs_vtime (تساوی شاخص)"),
        ("gs_ratio:index", "gs_ratio (نسبت ساده با شاخص)"),
        ("gs_entitled:index", "gs_entitled (استحقاق با شاخص)"),
        ("stride:index", "زمان‌بندی گام (Stride)"),
        ("rr:index", "چرخشی نوبتی (بدون وزن)"),
        ("fifo:index", "صف FIFO (دسته‌ای)"),
    ]
    rows = []
    for k, lbl in order:
        viols = t1["violations_above_q"][k]
        ratio = t1["max_lag_over_q"][k]
        mx = t1["max_lag_seen"][k]
        rows.append([
            lbl,
            f"{viols} از {t1['n_workloads']}",
            f"{ratio:.4f}q",
            f"{mx:.4f}",
        ])
    return rows


